  /// Get activity statistics
  Future<ActivityStatistics> getActivityStatistics({
    int? userId,
    int days = 30,
  }) async {
    try {
      final response = await _supabase
          .rpc('get_activity_statistics', params: {
            'p_user_id': userId,
            'p_days': days,
          })
          .select()
          .single();

      return ActivityStatistics.fromJson(response);
    } catch (e) {
      debugPrint('Error getting activity statistics: $e');
      // Return empty statistics on error
      return ActivityStatistics(
        totalActions: 0,
        uniqueUsers: 0,
        actionsByType: {},
        entitiesAffected: {},
        recentActivity: [],
      );
    }
  }

