import 'package:flutter/foundation.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import '../models/activity_log.dart';

/// Service for managing activity logs and audit trail
class ActivityLogService {
  final SupabaseClient _supabase = Supabase.instance.client;

  /// Log an activity action
  Future<int> logActivity({
    required int userId,
    required ActivityAction action,
    required EntityType entity,
    int? entityId,
    String? description,
    Map<String, dynamic>? oldValues,
    Map<String, dynamic>? newValues,
    String? ipAddress,
    String? userAgent,
  }) async {
    try {
      final log = ActivityLog(
        activityLogId: 0, // Will be generated by database
        userId: userId,
        action: action,
        entity: entity,
        entityId: entityId,
        description: description,
        oldValues: oldValues,
        newValues: newValues,
        ipAddress: ipAddress,
        userAgent: userAgent,
        createdAt: DateTime.now(),
      );

      final response = await _supabase
          .rpc('log_activity', params: {
            'p_user_id': userId,
            'p_action': action.value,
            'p_entity': entity.value,
            'p_entity_id': entityId,
            'p_description': description,
            'p_old_values': log.toJson()['OldValues'],
            'p_new_values': log.toJson()['NewValues'],
            'p_ip_address': ipAddress,
            'p_user_agent': userAgent,
          });

      // RPC returns the value directly, not wrapped in a list
      return response is int ? response : (response is List && response.isNotEmpty ? response.first as int : 0);
    } catch (e) {
      debugPrint('Error logging activity: $e');
      rethrow;
    }
  }

  /// Get all activity logs (admin only)
  Future<List<ActivityLog>> getAllActivityLogs({
    int? limit,
    int? offset,
    ActivityAction? filterAction,
    EntityType? filterEntity,
    DateTime? startDate,
    DateTime? endDate,
  }) async {
    try {
      // Fetch all logs with user info (RLS is disabled)
      final response = await _supabase
          .from('ActivityLog')
          .select('''
            *,
            User!fk_activitylog_user(FullName, Email)
          ''')
          .order('CreatedAt', ascending: false);

      List<Map<String, dynamic>> filtered = List<Map<String, dynamic>>.from(response as List).map((item) {
        // Flatten user data
        if (item['User'] != null) {
          item['userName'] = item['User']['FullName'];
          item['userEmail'] = item['User']['Email'];
        }
        return item;
      }).toList();

      // Apply filters manually
      if (filterAction != null) {
        filtered = filtered.where((item) => item['Action'] == filterAction.value).toList();
      }
      if (filterEntity != null) {
        filtered = filtered.where((item) => item['Entity'] == filterEntity.value).toList();
      }
      if (startDate != null) {
        filtered = filtered.where((item) {
          final createdAt = DateTime.parse(item['CreatedAt']);
          return createdAt.isAfter(startDate) || createdAt.isAtSameMomentAs(startDate);
        }).toList();
      }
      if (endDate != null) {
        filtered = filtered.where((item) {
          final createdAt = DateTime.parse(item['CreatedAt']);
          return createdAt.isBefore(endDate) || createdAt.isAtSameMomentAs(endDate);
        }).toList();
      }

      // Apply pagination
      if (offset != null) {
        filtered = filtered.skip(offset).toList();
      }
      if (limit != null) {
        filtered = filtered.take(limit).toList();
      }
      
      return filtered.map((json) => ActivityLog.fromJson(json)).toList();
    } catch (e) {
      debugPrint('Error getting all activity logs: $e');
      rethrow;
    }
  }

