  /// Search activity logs
  Future<List<ActivityLog>> searchActivityLogs({
    String? searchQuery,
    ActivityAction? filterAction,
    EntityType? filterEntity,
    DateTime? startDate,
    DateTime? endDate,
    int? limit = 50,
  }) async {
    try {
      // Fetch all logs with user info
      final response = await _supabase
          .from('ActivityLog')
          .select('''
            *,
            User!fk_activitylog_user(FullName, Email)
          ''')
          .order('CreatedAt', ascending: false);

      List<Map<String, dynamic>> filtered = List<Map<String, dynamic>>.from(response as List).map((item) {
        // Flatten user data
        if (item['User'] != null) {
          item['userName'] = item['User']['FullName'];
          item['userEmail'] = item['User']['Email'];
        }
        return item;
      }).toList();

      // Apply filters manually
      if (searchQuery != null && searchQuery.isNotEmpty) {
        filtered = filtered.where((item) {
          final description = item['Description']?.toString().toLowerCase() ?? '';
          return description.contains(searchQuery.toLowerCase());
        }).toList();
      }
      if (filterAction != null) {
        filtered = filtered.where((item) => item['Action'] == filterAction.value).toList();
      }
      if (filterEntity != null) {
        filtered = filtered.where((item) => item['Entity'] == filterEntity.value).toList();
      }
      if (startDate != null) {
        filtered = filtered.where((item) {
          final createdAt = DateTime.parse(item['CreatedAt']);
          return createdAt.isAfter(startDate) || createdAt.isAtSameMomentAs(startDate);
        }).toList();
      }
      if (endDate != null) {
        filtered = filtered.where((item) {
          final createdAt = DateTime.parse(item['CreatedAt']);
          return createdAt.isBefore(endDate) || createdAt.isAtSameMomentAs(endDate);
        }).toList();
      }

      // Apply limit
      if (limit != null) {
        filtered = filtered.take(limit).toList();
      }
      
      return filtered.map((json) => ActivityLog.fromJson(json)).toList();
    } catch (e) {
      debugPrint('Error searching activity logs: $e');
      rethrow;
    }
  }

  /// Get count of activity logs
  Future<int> getActivityLogCount({
    int? userId,
    ActivityAction? filterAction,
    EntityType? filterEntity,
    DateTime? startDate,
    DateTime? endDate,
  }) async {
    try {
      // Fetch all logs
      var query = _supabase.from('ActivityLog').select('ActivityLogId');
      
      if (userId != null) {
        query = query.eq('UserId', userId);
      }
      if (filterAction != null) {
        query = query.eq('Action', filterAction.value);
      }
      if (filterEntity != null) {
        query = query.eq('Entity', filterEntity.value);
      }
      if (startDate != null) {
        query = query.gte('CreatedAt', startDate.toIso8601String());
      }
      if (endDate != null) {
        query = query.lte('CreatedAt', endDate.toIso8601String());
      }

      final response = await query;
      return (response as List).length;
    } catch (e) {
      debugPrint('Error getting activity log count: $e');
      return 0;
    }
  }

  /// Clean up old activity logs (admin only - use with caution)
  Future<int> cleanupOldLogs({int daysToKeep = 365}) async {
    try {
      final response = await _supabase
          .rpc('cleanup_old_activity_logs', params: {
            'p_days_to_keep': daysToKeep,
          })
          .select();

      return response as int;
    } catch (e) {
      debugPrint('Error cleaning up old logs: $e');
      rethrow;
    }
  }

